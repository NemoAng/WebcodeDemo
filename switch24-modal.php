    function port_click(event) {
        if ($(this).hasClass(StatusClass.UNAVAIL)) {
            return;
        }

        const module_port = this.attributes[1].value.split("_");
        const panel_classes = $(this).parent().parent().attr('class').split(" ");
        const module_clicked = event.data.binding.module_clicked >= 15 ? event.data.binding.module_clicked - 14 : event.data.binding.module_clicked;

        if (event.data.binding.module_clicked !== 0 && event.data.binding.port_clicked !== 0) {
            if (event.data.binding.panel_clicked !== module_port[0]) {
                $('.' + event.data.binding.panel_clicked_name).children()[module_clicked - 1].children[event.data.binding.port_clicked - 1].classList.remove(StatusClass.CLICK);
            } else {
                $(this).parent().parent().children()[module_clicked - 1].children[event.data.binding.port_clicked - 1].classList.remove(StatusClass.CLICK);
            }
        }

        event.data.binding.panel_clicked = module_port[0];
        event.data.binding.module_clicked = module_port[1];
        event.data.binding.port_clicked = module_port[2];

        event.data.binding.panel_clicked_name = panel_classes[0];

        let module = event.data.binding.module_ports[event.data.binding.module_clicked - 1].location;
        let type = event.data.binding.module_ports[event.data.binding.module_clicked - 1].type.toUpperCase();

        let relay = event.data.binding.port_clicked;
        let group = event.data.binding.module_ports[event.data.binding.module_clicked - 1].ports[relay - 1]['port_group'];

        let func = event.data.binding.module_ports[event.data.binding.module_clicked - 1].ports[relay - 1]['port_func'];
        let name = event.data.binding.module_ports[event.data.binding.module_clicked - 1].ports[relay - 1]['port_name'];

        port_info({ module: module, type: type, relay: relay, group: group, func: func, name: name });

        $(this).addClass(StatusClass.CLICK);
    }

