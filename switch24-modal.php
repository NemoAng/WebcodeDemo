                module_ports[element['module_num'] - 1]['ports'][element['output_num'] - 1]['switch_cfged'] = true;
            } else {
                if (element['is_cfged_other'] === '1') {
                    module_ports[element['module_num_other'] - 1]['ports'][element['output_num_other'] - 1]['switch_cfged'] = true;
                }
            }
        });

        module_ios.push(module_ports);

        module_ios.forEach(function (module_io, index) {
            var __module_ports = module_ios[module_ios.length - 1];

            if (index !== module_ios.length - 1) {
                var __module = module_io['module_num'];
                var __port = module_io['output_num'];

                __module_ports.forEach((m_p) => {
                    if (__module == m_p['num']) {
                        var ports = m_p['ports'];

                        ports.forEach((port) => {
                            if (__port == port['port_num'] && port['switch_cfged']) {
                                // $('.overlay' + ' ' + '.' + GRID_HEADER + module_io['module_num']).children().eq(module_io['output_num'] - 1).addClass(StatusClass.OCCUP);
                                if (__module < 15) {
                                    if (_main_board == 1) {
                                        $(`.overlay:eq(1) .${GRID_HEADER}${module_io['module_num']}`).children().eq(module_io['output_num'] - 1).addClass(StatusClass.OCCUP);
                                    } else {
                                        $(`.overlay:eq(0) .${GRID_HEADER}${module_io['module_num']}`).children().eq(module_io['output_num'] - 1).addClass(StatusClass.OCCUP);
                                    }
                                } else if (__module < 28) {
                                    if (_ext_board == 1) {
                                        $(`.overlay:eq(3) .${GRID_HEADER}${module_io['module_num']}`).children().eq(module_io['output_num'] - 1).addClass(StatusClass.OCCUP);
                                    } else {
                                        $(`.overlay:eq(2) .${GRID_HEADER}${module_io['module_num']}`).children().eq(module_io['output_num'] - 1).addClass(StatusClass.OCCUP);
                                    }
                                }

                                return;
                            }
                        });
                    }
                });
            }
        });
    }

