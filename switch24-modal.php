            type: "POST",
            async: false,
            url: "/common/afxptc/php/selectAutoflexType.php",
            error: function (xhr, ajaxOptions, thrownError) {
                console.log(xhr);
            },
            success: function (data) {
                panels = JSON.parse(data);

                panels_board['main_board'] = panels[0].main_board;
                panels_board['main_desc'] = panels[0].main_desc;
                panels_board['ext_board'] = panels[0].ext_board;
