    function setModuleNumConfig(from_backend, settings) {
        const jijiwaiwai = JSON.parse(from_backend);

        let moduals = jijiwaiwai['moduals'];
        let moduals_ios = jijiwaiwai['moduals_ios'];

        settings['module_current'] = parseInt(jijiwaiwai['current_switch']['module_num']);
        settings['port_current'] = parseInt(jijiwaiwai['current_switch']['output_num']);
        settings['configed_current'] = jijiwaiwai['current_switch']['is_cfged'];

        settings['panel_modules'] = parseInt(jijiwaiwai['modual_total']);
        settings['panel_main_modules'] = parseInt(jijiwaiwai['modual_main']['count']);
        settings['panel_extend_modules'] = parseInt(jijiwaiwai['modual_expan']['count']);

        moduals.forEach(function (module, index) {
            let m_num = parseInt(module['module_num']);
            let m_type = module['module_type'];

            settings['module_ports'][m_num - 1]['viable'] = true;
            settings['module_ports'][m_num - 1]['type'] = moduleType[m_type];
        });

        moduals_ios.forEach(function (module_io, index) {
            let m_num = parseInt(module_io['module_num']);
            let o_num = parseInt(module_io['output_num']);

            settings['module_ports'][m_num - 1]['ports'][o_num - 1]['port_status'] = StatusClass.AVAIL;
            settings['module_ports'][m_num - 1]['ports'][o_num - 1]['port_func'] = module_io['function'];
            settings['module_ports'][m_num - 1]['ports'][o_num - 1]['port_group'] = module_io['equipment_group'];
            settings['module_ports'][m_num - 1]['ports'][o_num - 1]['port_name'] = module_io['relay_description'];
        });
    }

